export default function AdminLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  const pathname = usePathname();
  const router = useRouter();
  const [isAuthed, setIsAuthed] = useState<boolean | null>(null);
  const isLoginPage = pathname === "/admin/login";

  // Check auth on mount (runs on every page but only redirects on non-login pages)
  useEffect(() => {
    if (isLoginPage) {
      setIsAuthed(true); // Skip auth check on login page
      return;
    }

    async function checkAuth() {
      try {
        const res = await fetch("/api/admin/products?limit=1");
        if (res.status === 401) {
          router.replace("/admin/login");
          return;
        }
        setIsAuthed(true);
      } catch {
        router.replace("/admin/login");
      }
    }
    checkAuth();
  }, [router, isLoginPage]);

  // Login page — render children only (no sidebar)
  if (isLoginPage) {
    return <>{children}</>;
  }

  // Loading state while checking auth
  if (isAuthed === null) {
    return (
      <div className="flex min-h-screen items-center justify-center bg-background">
        <div className="text-center">
          <div className="h-8 w-8 mx-auto animate-spin rounded-full border-2 border-accent border-t-transparent" />
          <p className="mt-4 text-sm text-muted">Loading admin...</p>
        </div>
      </div>
    );
  }

  return (
    <div className="flex min-h-screen bg-background">
      {/* Sidebar */}
      <aside className="fixed left-0 top-0 z-40 h-full w-60 border-r border-border bg-surface">
        <div className="flex h-16 items-center px-6 border-b border-border">
          <Link href="/admin/dashboard" className="font-[family-name:var(--font-playfair)] text-lg font-bold text-accent">
            CD Admin
          </Link>
        </div>

        <nav className="mt-4 px-3 space-y-1">
          {NAV_ITEMS.map((item) => {
            const isActive = pathname.startsWith(item.href);
            return (
              <Link
                key={item.href}
                href={item.href}
                className={`flex items-center gap-3 rounded-lg px-3 py-2.5 text-sm transition-colors ${
                  isActive
                    ? "bg-accent/10 text-accent font-medium"
                    : "text-muted hover:bg-surface-hover hover:text-foreground"
                }`}
              >
                <svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" strokeWidth={1.5} stroke="currentColor" className="h-5 w-5">
                  <path strokeLinecap="round" strokeLinejoin="round" d={item.icon} />
                </svg>
                {item.label}
              </Link>
            );
          })}
        </nav>

        {/* Footer */}
        <div className="absolute bottom-0 left-0 right-0 border-t border-border p-4">
          <Link
            href="/"
            className="flex items-center gap-2 text-xs text-muted hover:text-foreground transition-colors"
          >
            <svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" strokeWidth={1.5} stroke="currentColor" className="h-4 w-4">
              <path strokeLinecap="round" strokeLinejoin="round" d="M13.5 6H5.25A2.25 2.25 0 0 0 3 8.25v10.5A2.25 2.25 0 0 0 5.25 21h10.5A2.25 2.25 0 0 0 18 18.75V10.5m-10.5 6L21 3m0 0h-5.25M21 3v5.25" />
            </svg>
            View Store
          </Link>
        </div>
      </aside>

      {/* Main Content */}
      <main className="flex-1 ml-60">
        <div className="p-8">{children}</div>
      </main>
    </div>
  );
}
